#!/usr/bin/env node
/**
 * Builds the isometric product scenes as self-contained Mintlify snippets.
 *
 * Source of truth is the marketing site (cloudthinker-landing-page):
 *   apps/web/components/iso-motion.tsx            shared kit
 *   apps/web/components/agentic-workflow-stage.tsx homepage workflow
 *   apps/web/app/.../_components/*-stage.tsx       one scene per product
 *
 * Mintlify only exposes a snippet's exports, so everything a scene needs is
 * inlined into one exported component and created once (useMemo), which keeps
 * helper component identities stable across animation frames.
 *
 * Usage: node scripts/build-iso-scenes.mjs [path/to/cloudthinker-landing-page]
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const landing = resolve(
  process.argv[2] ?? join(here, '../../cloudthinker-landing-page'),
);
const web = join(landing, 'apps/web');
const require = createRequire(join(landing, 'package.json'));
const ts = require('typescript');

const SCENES = [
  {
    name: 'WorkflowScene',
    file: 'components/agentic-workflow-stage.tsx',
    stage: 'AgenticWorkflowStage',
  },
  {
    name: 'ResolveScene',
    file: 'app/(marketing)/(products)/(features)/resolve/_components/resolve-stage.tsx',
    stage: 'ResolveStage',
  },
  {
    name: 'ReviewScene',
    file: 'app/(review)/code-review/_components/review-stage.tsx',
    stage: 'ReviewStage',
  },
  {
    name: 'CyberScene',
    file: 'app/(cyber)/cyber/_components/cyber-proof-stage.tsx',
    stage: 'CyberProofStage',
  },
  {
    name: 'OptimizeScene',
    file: 'app/(optimize)/optimize/_components/optimize-stage.tsx',
    stage: 'OptimizeStage',
  },
  {
    name: 'CustomizeScene',
    file: 'app/(marketing)/(products)/(features)/customize/_components/customize-stage.tsx',
    stage: 'CustomizeStage',
  },
  {
    name: 'AutomationScene',
    file: 'app/(automation)/automation/_components/automation-stage.tsx',
    stage: 'AutomationStage',
  },
  {
    name: 'OnCallScene',
    file: 'app/(oncall)/oncall/_components/oncall-war-room.tsx',
    stage: 'OnCallWarRoomStage',
  },
];

const toJs = (src) =>
  ts.transpileModule(src, {
    compilerOptions: {
      jsx: ts.JsxEmit.Preserve,
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.ESNext,
      verbatimModuleSyntax: false,
    },
  }).outputText;

// Drop imports, 'use client' and export keywords; the code is inlined.
const strip = (js) =>
  js
    .replace(/^['"]use client['"];?\s*$/m, '')
    .replace(/^import[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^import\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^export\s+(?=(const|function|let|class)\b)/gm, '')
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '');

let kit = strip(toJs(readFileSync(join(web, 'components/iso-motion.tsx'), 'utf8')));
// No next-themes on Mintlify: follow the `dark` class on <html>.
kit = kit.replace(
  /const\s*\{\s*resolvedTheme\s*\}\s*=\s*useTheme\(\);/,
  `const [resolvedTheme, setResolvedTheme] = useState('dark');
    useEffect(() => {
      const read = () =>
        setResolvedTheme(
          document.documentElement.classList.contains('dark') ? 'dark' : 'light',
        );
      read();
      const mo = new MutationObserver(read);
      mo.observe(document.documentElement, { attributes: true, attributeFilter: ['class'] });
      return () => mo.disconnect();
    }, []);`,
);
if (kit.includes('useTheme')) throw new Error('useTheme replacement failed');

const indent = (s, n) =>
  s
    .split('\n')
    .map((l) => (l.trim() ? ' '.repeat(n) + l : l))
    .join('\n');

const out = join(here, '../snippets/iso');
mkdirSync(out, { recursive: true });

for (const scene of SCENES) {
  const body = strip(toJs(readFileSync(join(web, scene.file), 'utf8')));
  const file = `/* Generated by scripts/build-iso-scenes.mjs from cloudthinker-landing-page.
 * Do not edit by hand: change the source scene, then re-run the script. */

export const ${scene.name} = ({ className }) => {
  const Stage = React.useMemo(() => {
    const {
      createContext,
      useContext,
      useEffect,
      useLayoutEffect,
      useRef,
      useState,
    } = React;
${indent(kit, 4)}
${indent(body, 4)}
    return ${scene.stage};
  }, []);
  return (
    <div className={className ?? 'ct-iso-scene'}>
      <Stage className="ct-iso-svg" />
    </div>
  );
};
`;
  const name = scene.name.replace(/Scene$/, '').toLowerCase();
  writeFileSync(join(out, `${name}.jsx`), file);
  console.log('wrote', `snippets/iso/${name}.jsx`, `${(file.length / 1024).toFixed(0)} KB`);
}
